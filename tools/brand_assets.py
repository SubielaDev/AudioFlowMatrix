"""Regenerates the app icon and the embedded GUI wordmark from docs/assets.

    python tools/brand_assets.py

Outputs src/app/app.ico (AF monogram on a dark tile with rounded corners) and
src/app/BrandLogo.inc (wordmark, its black background turned into transparency so it blends
into the interface). Requires Pillow.
"""

from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / "docs" / "assets"
APP = ROOT / "src" / "app"

WORDMARK_HEIGHT = 72  # texture height in px; drawn at ~36 px on 1x displays
ICON_SIZES = [16, 24, 32, 48, 64, 128, 256]
CORNER_RADIUS = 0.22  # of the icon size
TILE_COLOR = (30, 36, 48)  # icon background: dark slate, a little lighter than black


def content_bbox(img: Image.Image, threshold: int = 40):
    mask = img.convert("L").point(lambda v: 255 if v > threshold else 0)
    return mask.getbbox()


def black_to_alpha(src: Image.Image) -> Image.Image:
    """Logo on black -> straight-alpha RGBA: the brightest channel is the coverage."""
    out = bytearray()
    rgb = src.convert("RGB").tobytes()
    for i in range(0, len(rgb), 3):
        r, g, b = rgb[i], rgb[i + 1], rgb[i + 2]
        a = max(r, g, b)
        if a < 24:  # JPEG noise in the black background
            out += bytes((0, 0, 0, 0))
            continue
        out += bytes((min(255, r * 255 // a), min(255, g * 255 // a), min(255, b * 255 // a), a))
    return Image.frombytes("RGBA", src.size, bytes(out))


def wordmark() -> None:
    src = Image.open(ASSETS / "logo.jpg").convert("RGB")
    left, top, right, bottom = content_bbox(src)
    pad = 8
    src = src.crop((left - pad, top - pad, right + pad, bottom + pad))
    width = round(src.width * WORDMARK_HEIGHT / src.height)
    src = src.resize((width, WORDMARK_HEIGHT), Image.LANCZOS)

    out = black_to_alpha(src).tobytes()

    lines = [
        "// Generated by tools/brand_assets.py from docs/assets/logo.jpg. Do not edit.",
        f"constexpr int kWordmarkWidth = {width};",
        f"constexpr int kWordmarkHeight = {WORDMARK_HEIGHT};",
        "constexpr unsigned char kWordmarkRgba[] = {",
    ]
    for i in range(0, len(out), 32):
        lines.append("    " + ",".join(str(v) for v in out[i:i + 32]) + ",")
    lines.append("};")
    (APP / "BrandLogo.inc").write_text("\n".join(lines) + "\n", encoding="ascii")


def icon() -> None:
    src = Image.open(ASSETS / "icon.jpg").convert("RGB")
    # The monogram sits above the "MATRIX" caption; only the monogram stays legible at icon sizes.
    monogram = src.crop((0, 0, src.width, round(src.height * 0.66)))
    left, top, right, bottom = content_bbox(monogram)
    glyphs = monogram.crop((left, top, right, bottom))
    # Extra margin so the monogram clears the rounded corners.
    side = round(max(glyphs.width, glyphs.height) * 1.3)
    square = Image.new("RGB", (side, side))
    square.paste(glyphs, ((side - glyphs.width) // 2, (side - glyphs.height) // 2))
    # Tile in TILE_COLOR with rounded corners: only the area outside the corners is
    # transparent. The monogram is lifted off the artwork's black (scaled on black first, so
    # its anti-aliased edges carry no dark fringe) and composited onto the tile colour. The
    # corner mask is drawn at 4x and scaled down per size for smooth corners.
    frames = []
    for s in sorted(ICON_SIZES, reverse=True):
        tile = Image.new("RGBA", (s, s), TILE_COLOR + (255,))
        tile.alpha_composite(black_to_alpha(square.resize((s, s), Image.LANCZOS)))
        big = s * 4
        mask = Image.new("L", (big, big), 0)
        ImageDraw.Draw(mask).rounded_rectangle((0, 0, big - 1, big - 1), radius=round(big * CORNER_RADIUS), fill=255)
        tile.putalpha(mask.resize((s, s), Image.LANCZOS))
        frames.append(tile)
    frames[0].save(APP / "app.ico", format="ICO", sizes=[f.size for f in frames], append_images=frames[1:])


if __name__ == "__main__":
    wordmark()
    icon()
